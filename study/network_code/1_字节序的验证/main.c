#include "INC_head.h"

/*验证主机的存储结构式大端还是小端
    大端：高位字节存放在低地址  低位字节存放在高地址 网络字节序
    小端：高位字节存放在高地址  低位字节存放在低地址 x86 主机字节序
*/
int main()
{

    uint32_t a = 0x12345678;
    uint8_t a2 = *(uint8_t *)&a;
    if (a2 == 0x78)
    {

        // 当a2的值为0x78时，说明a的低地址存放的是0x78，即低位字节存放在低地址，所以是小端
        printf("小端\n");
    }

    return 0;
}